"""General Weidian order admin page API.

Reads the sanitized canonical order store generated by fan-hub. Tencent is the
primary: it owns Weidian cookies, QQ/Feishu credentials and the root worker.
Aliyun forwards reads/jobs to Tencent through the existing shared-state SSH
peer, so no Weidian credentials or QQ configs are needed on the public node.
"""

from __future__ import annotations

import hmac
import json
import re
import subprocess
import threading
import time
from pathlib import Path
from typing import Any

from fastapi import APIRouter, Body, Cookie, Depends, Header, HTTPException, Request, Response

from website import config as cfg
from website import redblue_ledger_api
from website.shared_runtime_state import SharedStatePeerError, peer_command

router = APIRouter(prefix="/api/weidian-orders", tags=["微店订单"])

AUTH_COOKIE = "weidian_orders_auth"
AUTH_COOKIE_PATH = "/api/weidian-orders"

FANHUB_ROOT = Path("/home/snh48-fan-hub")
FANHUB_PYTHON = FANHUB_ROOT / "venv" / "bin" / "python3"
FANHUB_CLI = FANHUB_ROOT / "scripts" / "weidian" / "order_admin.py"
JOB_ID_RE = re.compile(r"^[a-f0-9]{32}$")
CACHE_TTL_SECONDS = 8

_cache_lock = threading.Lock()
_cache_at = 0.0
_cache_data: dict[str, Any] | None = None


def _primary() -> bool:
    return bool(cfg.SHARED_STATE_IS_PRIMARY or not cfg.SHARED_STATE_SYNC_ENABLED)


def _expected_password() -> str:
    return str(cfg.REDBLUE_LEDGER_PASSWORD or "")


def _cookie_token(password: str) -> str:
    return redblue_ledger_api._cookie_token(password)


def verify_weidian_orders_password(
    request: Request,
    x_redblue_password: str = Header(None, alias="X-Redblue-Password"),
    x_weidian_password: str = Header(None, alias="X-Weidian-Orders-Password"),
    weidian_orders_auth: str = Cookie(None, alias=AUTH_COOKIE),
):
    expected = _expected_password()
    if not expected:
        raise HTTPException(status_code=403, detail="微店订单页未启用")
    token = _cookie_token(expected)
    if weidian_orders_auth and hmac.compare_digest(weidian_orders_auth, token):
        return True
    for supplied in (x_redblue_password, x_weidian_password):
        if supplied and hmac.compare_digest(supplied, expected):
            return True
    if not weidian_orders_auth and not x_redblue_password and not x_weidian_password:
        redblue_ledger_api.check_redblue_login_limit(request)
        raise HTTPException(status_code=401, detail="需要密码")
    redblue_ledger_api.check_redblue_login_limit(request)
    raise HTTPException(status_code=403, detail="密码错误")


@router.post("/login")
def login(payload: dict[str, Any], response: Response, request: Request):
    expected = _expected_password()
    if not expected:
        raise HTTPException(status_code=403, detail="微店订单页未启用")
    supplied = str(payload.get("password") or "")
    if not hmac.compare_digest(supplied, expected):
        redblue_ledger_api.check_redblue_login_limit(request)
        raise HTTPException(status_code=403, detail="密码错误")
    response.set_cookie(
        key=AUTH_COOKIE,
        value=_cookie_token(expected),
        max_age=redblue_ledger_api.AUTH_COOKIE_MAX_AGE,
        path=AUTH_COOKIE_PATH,
        httponly=True,
        secure=cfg.SECURE_COOKIES,
        samesite="strict",
    )
    return {"ok": True}


@router.post("/logout")
def logout(response: Response):
    response.delete_cookie(AUTH_COOKIE, path=AUTH_COOKIE_PATH)
    return {"ok": True}


def _clear_cache() -> None:
    global _cache_at, _cache_data
    with _cache_lock:
        _cache_at = 0.0
        _cache_data = None


def _run_local(action: str, payload: dict[str, Any]) -> dict[str, Any]:
    try:
        proc = subprocess.run(
            [str(FANHUB_PYTHON), str(FANHUB_CLI), action, "--json"],
            input=json.dumps(payload, ensure_ascii=False),
            text=True,
            capture_output=True,
            timeout=45,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise HTTPException(status_code=503, detail=f"fan-hub 订单工具不可用：{exc}") from exc
    output = (proc.stdout or "").strip()
    if proc.returncode != 0:
        detail = output or (proc.stderr or "").strip() or f"exit {proc.returncode}"
        try:
            parsed = json.loads(detail)
            detail = str(parsed.get("error") or detail)
        except json.JSONDecodeError:
            pass
        raise HTTPException(status_code=502, detail=detail[:300])
    try:
        value = json.loads(output)
    except json.JSONDecodeError as exc:
        raise HTTPException(status_code=502, detail="fan-hub 返回无效 JSON") from exc
    if not isinstance(value, dict):
        raise HTTPException(status_code=502, detail="fan-hub 返回格式无效")
    return value


def _peer(action: str, payload: dict[str, Any]) -> dict[str, Any]:
    try:
        response = peer_command("weidian-admin", {"action": action, "payload": payload})
    except SharedStatePeerError as exc:
        raise HTTPException(status_code=exc.status_code or 503, detail=str(exc)) from exc
    if not isinstance(response, dict):
        raise HTTPException(status_code=502, detail="对端返回格式无效")
    response.pop("ok", None)
    return response


def _call(action: str, payload: dict[str, Any]) -> dict[str, Any]:
    if _primary():
        return _run_local(action, payload)
    return _peer(action, payload)


@router.get("/data")
def weidian_orders_data(_=Depends(verify_weidian_orders_password)):
    global _cache_at, _cache_data
    now = time.time()
    with _cache_lock:
        if _cache_data is not None and now - _cache_at < CACHE_TTL_SECONDS:
            return _cache_data
    data = _call("snapshot", {})
    with _cache_lock:
        _cache_at = time.time()
        _cache_data = data
    return data


@router.post("/jobs")
def create_weidian_order_job(
    payload: dict[str, Any] = Body(default={}),
    _=Depends(verify_weidian_orders_password),
):
    job_type = str(payload.get("type") or "").strip()
    if job_type not in {"refresh", "ship", "rebroadcast"}:
        raise HTTPException(status_code=422, detail="不支持的任务类型")
    _clear_cache()
    return _call("job-submit", payload)


@router.get("/jobs/{job_id}")
def get_weidian_order_job(job_id: str, _=Depends(verify_weidian_orders_password)):
    if not JOB_ID_RE.fullmatch(job_id):
        raise HTTPException(status_code=422, detail="无效的任务 ID")
    result = _call("job-result", {"job_id": job_id})
    if str(result.get("status") or "") == "done":
        _clear_cache()
    return result


@router.post("/name")
def set_weidian_order_name(
    payload: dict[str, Any] = Body(default={}),
    _=Depends(verify_weidian_orders_password),
):
    order_id = str(payload.get("order_id") or "").strip()
    name = str(payload.get("name") or "").strip()
    if not order_id or not name:
        raise HTTPException(status_code=422, detail="订单号和昵称不能为空")
    if len(name) > 120:
        raise HTTPException(status_code=422, detail="昵称过长")
    local = _run_local("set-name", {"order_id": order_id, "name": name})
    remote_error = ""
    try:
        _peer("set-name", {"order_id": order_id, "name": name})
    except HTTPException as exc:
        remote_error = str(exc.detail)
    _clear_cache()
    return {"result": local, "remote_synced": not remote_error, "remote_error": remote_error}
